import { NextResponse } from 'next/server';
import { createClient } from '@supabase/supabase-js';
import crypto from 'crypto';

// We use the service role key to bypass RLS when creating tasks from a backend webhook
const supabase = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL!,
  process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!
);

export async function POST(req: Request) {
  try {
    const configuredSecret = process.env.SUPABASE_WEBHOOK_SECRET;
    
    // Fail closed if the secret is missing from the environment
    if (!configuredSecret) {
      console.error("CRITICAL: SUPABASE_WEBHOOK_SECRET is not configured.");
      return NextResponse.json({ error: 'Service Unavailable' }, { status: 503 });
    }

    const providedSecret = req.headers.get('x-supabase-webhook-secret');
    
    if (!providedSecret) {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
    }

    // Timing-safe comparison
    const configuredBuffer = Buffer.from(configuredSecret);
    const providedBuffer = Buffer.from(providedSecret);

    if (configuredBuffer.length !== providedBuffer.length || !crypto.timingSafeEqual(configuredBuffer, providedBuffer)) {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
    }

    const payload = await req.json();

    // payload from Supabase webhook: { type: 'INSERT' | 'UPDATE', table: 'enquiries', record: {...}, old_record: {...} }
    const { type, table, record, old_record } = payload;

    if (table !== 'enquiries') {
      return NextResponse.json({ message: 'Ignored: Not enquiries table' });
    }

    // Fetch active automations
    const { data: automations, error: autoError } = await supabase
      .from('workflow_automations')
      .select('*')
      .eq('is_active', true);

    if (autoError) throw autoError;
    if (!automations || automations.length === 0) {
      return NextResponse.json({ message: 'No active automations found' });
    }

    // Process each automation rule
    for (const rule of automations) {
      let isMatch = false;

      // 1. Evaluate "Lead Created"
      if (rule.trigger_type === 'lead_created' && type === 'INSERT') {
        isMatch = true; // Could add source checks here using rule.trigger_conditions
      }
      
      // 2. Evaluate "Lead Status Updated"
      if (rule.trigger_type === 'lead_status_updated' && type === 'UPDATE') {
        const targetStatus = rule.trigger_conditions?.target_status;
        if (targetStatus && record.status === targetStatus && old_record.status !== targetStatus) {
          isMatch = true;
        }
      }

      if (isMatch) {
        console.log(`Automation Matched: ${rule.name}`);
        
        // Execute Action: Create Task
        if (rule.action_type === 'create_task') {
          const taskData = {
            student_name: record.full_name,
            phone: record.mobile,
            counselor_name: rule.action_payload?.assignee || 'Auto-Assigned',
            notes: `${rule.action_payload?.task_title || 'Automated Task'} (Auto-generated by workflow)`,
            follow_up_date: new Date().toISOString().split('T')[0],
            status: 'pending'
          };
          
          await supabase.from('follow_ups').insert([taskData]);
          console.log('Automated Task created successfully.');
        }
        
        // Execute Action: Send Email
        if (rule.action_type === 'send_email') {
          console.log(`Triggering notification with template: ${rule.action_payload?.template}`);
          // In a real production environment, use absolute URL like process.env.NEXT_PUBLIC_SITE_URL
          // For now, we simulate an internal async call or just log if not possible.
          try {
             await fetch(new URL('/api/notify', req.url).toString(), {
               method: 'POST',
               headers: { 'Content-Type': 'application/json' },
               body: JSON.stringify({
                 to_email: record.email,
                 subject: `Update on your Enquiry: ${rule.action_payload?.template}`,
                 message: `Hello ${record.full_name}, this is an automated update regarding your enquiry.`,
                 type: 'email'
               })
             });
          } catch (e) {
             console.error("Failed to trigger notify API", e);
          }
        }
      }
    }

    return NextResponse.json({ success: true, message: 'Webhook processed' });

  } catch (error) {
    console.error('Webhook error:', error);
    return NextResponse.json({ error: 'Internal Server Error' }, { status: 500 });
  }
}
